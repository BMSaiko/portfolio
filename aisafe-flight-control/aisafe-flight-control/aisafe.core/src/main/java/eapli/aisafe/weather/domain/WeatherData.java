package eapli.aisafe.weather.domain;

import eapli.aisafe.aircontrolmanagement.domain.AirControlArea;
import eapli.aisafe.generic.domain.TimePeriod;

import jakarta.persistence.*;
import eapli.framework.domain.model.AggregateRoot;

/**
 * Aggregate root that represents a weather data record registered in the system.
 *
 * <p>
 * A weather data record describes the meteorological conditions observed or
 * forecast for a specific {@link AirControlArea} during a specific
 * {@link TimePeriod}. It includes temperature, wind speed, wind direction,
 * humidity and atmospheric pressure.
 * </p>
 *
 * <p>
 * This aggregate is used by weather-related use cases such as registering
 * weather data, importing bulk weather data, consulting weather data by area
 * and date, and associating weather data with flight plans.
 * </p>
 *
 * <p>
 * The database identity is generated automatically and is represented by a
 * {@link Long}. Two weather data records are considered the same aggregate only
 * when they share the same persisted identity.
 * </p>
 */
@Entity
@Table(name = "T_WEATHER_DATA")
public class WeatherData implements AggregateRoot<Long> {

    /**
     * Technical database identifier of the weather data record.
     *
     * <p>
     * This value is generated by the persistence provider and should not be
     * assigned manually by application code.
     * </p>
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Air control area to which this weather data applies.
     */
    @ManyToOne(optional = false)
    @JoinColumn(name = "AREA_CODE")
    private AirControlArea area;

    /**
     * Time period during which the weather data is valid.
     */
    @Embedded
    @AttributeOverrides({
            @AttributeOverride(name = "start", column = @Column(name = "period_start", nullable = false)),
            @AttributeOverride(name = "end", column = @Column(name = "period_end", nullable = false))
    })
    private TimePeriod period;

    /**
     * Temperature value for the selected area and time period.
     */
    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "temperature", nullable = false))
    private Temperature temperature;

    /**
     * Wind speed value for the selected area and time period.
     */
    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "wind_speed", nullable = false))
    private WindSpeed windSpeed;

    /**
     * Wind direction value for the selected area and time period.
     */
    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "wind_direction", nullable = false))
    private WindDirection windDirection;

    /**
     * Humidity value for the selected area and time period.
     */
    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "humidity", nullable = false))
    private Humidity humidity;

    /**
     * Atmospheric pressure value for the selected area and time period.
     */
    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "pressure", nullable = false))
    private Pressure pressure;

    /**
     * Protected constructor required by JPA.
     *
     * <p>
     * Application code should use the public constructor that enforces all
     * mandatory weather data invariants.
     * </p>
     */
    protected WeatherData() {}

    /**
     * Creates a weather data record for an air control area and time period.
     *
     * @param area the air control area to which the weather data applies
     * @param period the time period during which the data is valid
     * @param temperature the temperature value
     * @param windSpeed the wind speed value
     * @param windDirection the wind direction value
     * @param humidity the humidity value
     * @param pressure the atmospheric pressure value
     * @throws IllegalArgumentException if any argument is {@code null}
     */
    public WeatherData(AirControlArea area, TimePeriod period,
                       Temperature temperature, WindSpeed windSpeed,
                       WindDirection windDirection, Humidity humidity,
                       Pressure pressure) {
        setArea(area);
        setPeriod(period);
        setTemperature(temperature);
        setWindSpeed(windSpeed);
        setWindDirection(windDirection);
        setHumidity(humidity);
        setPressure(pressure);
    }

    /**
     * Defines the air control area for this weather data record.
     *
     * @param area the air control area
     * @throws IllegalArgumentException if {@code area} is {@code null}
     */
    private void setArea(AirControlArea area) {
        if (area == null) throw new IllegalArgumentException("Air control area is required");
        this.area = area;
    }

    /**
     * Defines the validity period for this weather data record.
     *
     * @param period the validity period
     * @throws IllegalArgumentException if {@code period} is {@code null}
     */
    private void setPeriod(TimePeriod period) {
        if (period == null) throw new IllegalArgumentException("Time period is required");
        this.period = period;
    }

    /**
     * Defines the temperature value.
     *
     * @param temperature the temperature value
     * @throws IllegalArgumentException if {@code temperature} is {@code null}
     */
    private void setTemperature(Temperature temperature) {
        if (temperature == null) throw new IllegalArgumentException("Temperature is required");
        this.temperature = temperature;
    }

    /**
     * Defines the wind speed value.
     *
     * @param windSpeed the wind speed value
     * @throws IllegalArgumentException if {@code windSpeed} is {@code null}
     */
    private void setWindSpeed(WindSpeed windSpeed) {
        if (windSpeed == null) throw new IllegalArgumentException("Wind speed is required");
        this.windSpeed = windSpeed;
    }

    /**
     * Defines the wind direction value.
     *
     * @param windDirection the wind direction value
     * @throws IllegalArgumentException if {@code windDirection} is {@code null}
     */
    private void setWindDirection(WindDirection windDirection) {
        if (windDirection == null) throw new IllegalArgumentException("Wind direction is required");
        this.windDirection = windDirection;
    }

    /**
     * Defines the humidity value.
     *
     * @param humidity the humidity value
     * @throws IllegalArgumentException if {@code humidity} is {@code null}
     */
    private void setHumidity(Humidity humidity) {
        if (humidity == null) throw new IllegalArgumentException("Humidity is required");
        this.humidity = humidity;
    }

    /**
     * Defines the atmospheric pressure value.
     *
     * @param pressure the atmospheric pressure value
     * @throws IllegalArgumentException if {@code pressure} is {@code null}
     */
    private void setPressure(Pressure pressure) {
        if (pressure == null) throw new IllegalArgumentException("Pressure is required");
        this.pressure = pressure;
    }

    /**
     * Returns the generated database identifier.
     *
     * @return the weather data identifier, or {@code null} if not yet persisted
     */
    public Long id() { return id; }

    /**
     * Returns the air control area to which this weather data applies.
     *
     * @return the air control area
     */
    public AirControlArea area() { return area; }

    /**
     * Returns the time period during which this weather data is valid.
     *
     * @return the validity period
     */
    public TimePeriod period() { return period; }

    /**
     * Returns the temperature value.
     *
     * @return the temperature
     */
    public Temperature temperature() { return temperature; }

    /**
     * Returns the wind speed value.
     *
     * @return the wind speed
     */
    public WindSpeed windSpeed() { return windSpeed; }

    /**
     * Returns the wind direction value.
     *
     * @return the wind direction
     */
    public WindDirection windDirection() { return windDirection; }

    /**
     * Returns the humidity value.
     *
     * @return the humidity
     */
    public Humidity humidity() { return humidity; }

    /**
     * Returns the atmospheric pressure value.
     *
     * @return the pressure
     */
    public Pressure pressure() { return pressure; }

    /**
     * Returns the aggregate identity.
     *
     * @return the generated weather data identifier
     */
    @Override
    public Long identity() {
        return id;
    }

    /**
     * Checks whether another object represents the same weather data aggregate.
     *
     * <p>
     * Weather data records are considered the same only if both are persisted
     * and have the same generated identifier.
     * </p>
     *
     * @param other the object to compare with this weather data record
     * @return {@code true} if both objects represent the same aggregate;
     * otherwise {@code false}
     */
    @Override
    public boolean sameAs(Object other) {
        if (this == other) return true;
        if (!(other instanceof WeatherData)) return false;
        WeatherData that = (WeatherData) other;
        return id != null && id.equals(that.id);
    }
}